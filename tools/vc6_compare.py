"""Compare the procedures implemented in C++ and compiled by Visual C++ 6.0
with the original binaries.

Usage:
    python tools/vc6_compare.py --check tools/vc6_statuses.txt
    python tools/vc6_compare.py --update tools/vc6_statuses.txt

The workspace generated by tools/vc2005_to_vc6.py is built in Release by
MSDEV.EXE with the linker writing the maps (the environment variable
LINK=/MAP). A procedure implemented in C++ (marked in asm/native.asm of
its module) is found in the linked Blade.exe, BBLibc.dll or rOpenGL.dll
by its name in the map, the size of its code is taken from its object
file. Its bytes are compared with asm/raw.txt of the original binary
except the fields changed by the linker; the targets of these fields are
compared by name instead: a call or an address must refer to the
procedure, export or import of the same name as in the original binary,
when the original target has a known name.

A procedure is OK when its code is the code of the original binary, LINES
when only the line numbers passed to _assert differ, STACK when only the
layout of the stack differs too (the displacements of [ebp+N] and the
size of the frame in sub esp, N, found by the instructions of raw.txt),
DIFF otherwise. LINES and STACK aren't significant: the line numbers
follow the layout of the sources and the layout of the stack is fitted
later for the whole binary. tools/vc6_statuses.txt lists the significant
differences, the procedures DIFF or MISSING. --check fails when another
procedure (a new one or one that got worse) is DIFF or MISSING; a
procedure of the file which doesn't differ any more is only printed, the
file is updated from time to time by --update.
"""
import argparse
import os
import re
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# Module: (directory of the sources, objects, binary)
MODULES = {
    "Blade": ("src/Blade", "src/Blade", "install/bin/Blade.exe"),
    "BBLibc": ("src/BBLibc", "src/BBLibc", "install/bin/BBLibc.dll"),
    "rOpenGL": (
        "src/Raster/rOpenGL3", "src/Raster/rOpenGL3",
        "install/bin/Raster/rOpenGL.dll"),
}
STATUSES = ("OK", "LINES", "STACK", "DIFF", "MISSING")
SIGNIFICANT = ("DIFF", "MISSING")

IMAGE_SYM_DTYPE_FUNCTION = 0x20
IMAGE_SCN_LNK_COMDAT = 0x00001000
DIR32 = 0x0006
REL32 = 0x0014
RELOCATION_SIZES = {0x0006: 4, 0x0007: 4, 0x000A: 2, 0x000B: 4, 0x0014: 4}

raw_regexp = re.compile(r"^([0-9A-F]{8}): ([0-9A-F]+)\s+(.*)$")
export_regexp = re.compile(r"^\* Export: ([^,]+),")
import_regexp = re.compile(r"\b[A-Za-z_0-9]+\.(\S+)")
ebp_regexp = re.compile(r"\[ebp([+-])([0-9A-F]+)\]")


class ObjFile:
    """Functions and relocations of a COFF object file."""

    def __init__(self, file_name):
        with open(file_name, "rb") as f:
            data = f.read()
        _, n_sections, _, symbols_ptr, n_symbols, optional_size, _ = \
            struct.unpack("<HHIIIHH", data[:20])
        self.sections = []
        for i in range(n_sections):
            h = 20 + optional_size + i * 40
            (_, _, _, size, raw_ptr, relocs_ptr, _, n_relocs, _,
             characteristics) = struct.unpack("<8sIIIIIIHHI", data[h:h + 40])
            relocs = []
            for j in range(n_relocs):
                o = relocs_ptr + j * 10
                relocs.append(struct.unpack("<IIH", data[o:o + 10]))
            self.sections.append(
                (data[raw_ptr:raw_ptr + size], relocs, characteristics))
        self.symbols = {}
        self.functions = []
        strings = symbols_ptr + n_symbols * 18
        i = 0
        while i < n_symbols:
            o = symbols_ptr + i * 18
            name, value, section, sym_type, _, n_aux = struct.unpack(
                "<8sIhHBB", data[o:o + 18])
            if name[:4] == b"\0\0\0\0":
                p = strings + struct.unpack("<I", name[4:])[0]
                name = data[p:data.index(b"\0", p)]
            name = name.rstrip(b"\0").decode("latin-1")
            self.symbols[i] = name
            if sym_type == IMAGE_SYM_DTYPE_FUNCTION and section > 0:
                self.functions.append((name, value, section))
            i += 1 + n_aux

    def function(self, value, section_number):
        """Code, mask of the relocated bytes and relocations
        [(offset, type, target)] of a function."""
        data, relocs, characteristics = self.sections[section_number - 1]
        end = len(data)
        if not characteristics & IMAGE_SCN_LNK_COMDAT:
            for _, other, sec in self.functions:
                if sec == section_number and value < other < end:
                    end = other
        code = data[value:end]
        mask = [False] * len(code)
        relocations = []
        for addr, symbol, reloc_type in relocs:
            if not value <= addr < end:
                continue
            for i in range(addr, min(addr + RELOCATION_SIZES.get(reloc_type, 4), end)):
                mask[i - value] = True
            relocations.append((addr - value, reloc_type, self.symbols.get(symbol, "")))
        return code, mask, relocations


class Image:
    """Sections of a linked PE file."""

    def __init__(self, file_name):
        with open(file_name, "rb") as f:
            data = f.read()
        pe = struct.unpack("<I", data[0x3C:0x40])[0]
        n_sections, = struct.unpack("<H", data[pe + 6:pe + 8])
        optional_size, = struct.unpack("<H", data[pe + 20:pe + 22])
        self.base, = struct.unpack("<I", data[pe + 52:pe + 56])
        self.sections = []
        for i in range(n_sections):
            h = pe + 24 + optional_size + i * 40
            vsize, rva, rsize, rptr = struct.unpack("<IIII", data[h + 8:h + 24])
            self.sections.append((rva, max(vsize, rsize), data[rptr:rptr + rsize]))

    def read(self, va, size):
        rva = va - self.base
        for start, length, raw in self.sections:
            if start <= rva < start + length:
                chunk = raw[rva - start:rva - start + size]
                return chunk + b"\0" * (size - len(chunk))
        raise ValueError("address 0x%08X is not in the image" % va)


class Original:
    """Bytes, names of the targets and instructions of the original binary."""

    def __init__(self, asm_dir):
        self.memory = {}
        self.texts = {}
        self.names = {}
        export = None
        with open(os.path.join(asm_dir, "raw.txt"), encoding="cp1251", errors="replace") as f:
            for line in f:
                m = export_regexp.match(line)
                if m:
                    export = m.group(1)
                    continue
                m = raw_regexp.match(line.rstrip("\n"))
                if not m:
                    continue
                addr = int(m.group(1), 16)
                if export is not None:
                    self.names[addr] = export
                    export = None
                hex_bytes = m.group(2)
                for i in range(0, len(hex_bytes), 2):
                    self.memory[addr + i // 2] = int(hex_bytes[i:i + 2], 16)
                self.texts[addr] = m.group(3)
        native = open(os.path.join(asm_dir, "native.asm"), encoding="latin-1").read()
        implemented = set(int(a, 16) for a in re.findall(
            r"call l([0-9A-F]{8}); Implemented in c\+\+ code", native))
        self.implemented = {}
        with open(os.path.join(asm_dir, "procedures.inc"), encoding="latin-1") as f:
            for line in f:
                m = re.match(r"^l([0-9A-F]{8}) equ (\S+)", line)
                if m:
                    addr = int(m.group(1), 16)
                    self.names[addr] = m.group(2)
                    if addr in implemented:
                        self.implemented[m.group(2)] = addr

    def stack_fields(self, addr, size):
        """Offsets of the bytes of the layout of the stack in a procedure:
        the displacements of [ebp+N] and the size of the frame in
        sub esp, N."""
        res = set()
        for start in range(addr, addr + size):
            text = self.texts.get(start)
            if text is None:
                continue
            end = start + 1
            while end < addr + size and end not in self.texts:
                end += 1
            code = bytes(self.memory.get(a, 0) for a in range(start, end))
            m = ebp_regexp.search(text)
            if m:
                value = int(m.group(2), 16) * (-1 if m.group(1) == "-" else 1)
                field = (struct.pack("<b", value) if len(m.group(2)) <= 2
                         else struct.pack("<i", value))
                pos = code.find(field, 1)
                if pos > 0:
                    res.update(range(start - addr + pos, start - addr + pos + len(field)))
            elif text.startswith("sub esp,") and code[:2] in (b"\x83\xEC", b"\x81\xEC"):
                res.update(range(start - addr + 2, end - addr))
        return res

    def target(self, field_addr, value, reloc_type):
        if reloc_type == REL32:
            return self.names.get(field_addr + 4 + value)
        if value in self.names:
            return self.names[value]
        for a in range(field_addr, field_addr - 16, -1):
            if a in self.texts:
                m = import_regexp.search(self.texts[a])
                return import_name(m.group(1)) if m else None
        return None


def import_name(name):
    """Name of an imported procedure: __imp__GetDC@4 -> GetDC."""
    if name.startswith("__imp_"):
        name = name[len("__imp_"):]
    if not name.startswith("?"):
        name = re.sub(r"@\d+$", "", name.lstrip("_"))
    return name


def read_map(file_name):
    by_name, by_addr = {}, {}
    with open(file_name, encoding="latin-1") as f:
        for line in f:
            m = re.match(r"^ [0-9a-fA-F]{4}:[0-9a-fA-F]{8}\s+(\S+)\s+([0-9a-fA-F]{8})\s", line)
            if m:
                name, addr = m.group(1), int(m.group(2), 16)
                by_name.setdefault(name, addr)
                by_addr.setdefault(addr, name)
    return by_name, by_addr


def assert_lines(code, relocations):
    """Offsets and sizes of the __LINE__ immediates pushed for _assert."""
    res = []
    for off, _, target in relocations:
        if "_assert" not in target:
            continue
        p = off - 2 - 10
        if code[p - 2] == 0x6A:
            res.append((p - 1, 1))
        elif code[p - 5] == 0x68:
            res.append((p - 4, 4))
    return res


def compare_module(mod):
    src_dir, obj_dir, binary = (os.path.join(ROOT, p) for p in MODULES[mod])
    original = Original(os.path.join(src_dir, "asm"))
    image = Image(binary)
    map_file = os.path.splitext(binary)[0] + ".map"
    by_name, by_addr = read_map(map_file)
    res = {}
    for f in sorted(os.listdir(obj_dir)):
        if not f.lower().endswith(".obj"):
            continue
        obj = ObjFile(os.path.join(obj_dir, f))
        for name, value, section in obj.functions:
            addr = original.implemented.get(name)
            if addr is None or name in res:
                continue
            code, mask, relocations = obj.function(value, section)
            va = by_name.get(name)
            if va is None:
                res[name] = (addr, "MISSING", [])
                continue
            linked = image.read(va, len(code))
            diffs = [i for i in range(len(code))
                     if not mask[i] and original.memory.get(addr + i) != linked[i]]
            status = "OK"
            if diffs:
                lines = set(i for o, n in assert_lines(code, relocations)
                            for i in range(o, o + n))
                stack = original.stack_fields(addr, len(code))
                if all(i in lines for i in diffs):
                    status = "LINES"
                elif all(i in lines or i in stack for i in diffs):
                    status = "STACK"
                else:
                    status = "DIFF"
            targets = []
            # The fields of a differing code are at other offsets
            for off, reloc_type, _ in relocations if status != "DIFF" else []:
                if reloc_type not in (REL32, DIR32):
                    continue
                fmt = "<i" if reloc_type == REL32 else "<I"
                ours = struct.unpack(fmt, linked[off:off + 4])[0]
                orig = struct.unpack(fmt, bytes(
                    original.memory.get(addr + off + i, 0) for i in range(4)))[0]
                expected = original.target(addr + off, orig, reloc_type)
                target = va + off + 4 + ours if reloc_type == REL32 else ours
                actual = by_addr.get(target)
                if actual and actual.startswith("__imp_"):
                    actual = import_name(actual)
                if expected and actual and expected != actual:
                    targets.append("+%04X %s instead of %s" % (off, actual, expected))
            if targets:
                status = "DIFF"
            res[name] = (addr, status, targets)
    for name, addr in original.implemented.items():
        res.setdefault(name, (addr, "MISSING", []))
    return res


def compare():
    statuses = {}
    for mod in MODULES:
        res = compare_module(mod)
        counts = [sum(1 for v in res.values() if v[1] == s) for s in STATUSES]
        print("%s: %s" % (mod, ", ".join(
            "%s %d" % (s, n) for s, n in zip(STATUSES, counts))))
        for name, (addr, status, targets) in sorted(res.items(), key=lambda kv: kv[1][0]):
            statuses[(mod, name)] = (addr, status)
            for t in targets:
                print("    %08X %s: %s" % (addr, name, t))
    return statuses


def format_statuses(statuses):
    lines = [
        "# Procedures implemented in C++ compiled by VC6 differing from the",
        "# original binaries (DIFF, MISSING), written by:",
        "# python tools/vc6_compare.py --update tools/vc6_statuses.txt"]
    for (mod, name), (addr, status) in sorted(
            statuses.items(), key=lambda kv: (kv[0][0], kv[1][0])):
        if status in SIGNIFICANT:
            lines.append("%s %08X %s %s" % (mod, addr, status, name))
    return "\n".join(lines) + "\n"


def read_statuses(file_name):
    statuses = {}
    with open(file_name, encoding="latin-1") as f:
        for line in f:
            if line.startswith("#") or not line.strip():
                continue
            mod, addr, status, name = line.split()
            statuses[(mod, name)] = (int(addr, 16), status)
    return statuses


def check(statuses, file_name):
    """Fail when a procedure missing in the file differs significantly."""
    expected = read_statuses(file_name)
    failed = changed = False
    for key in sorted(set(statuses) | set(expected)):
        mod, name = key
        new = statuses.get(key, (None, "REMOVED"))[1]
        old = expected.get(key, (None, None))[1]
        if new in SIGNIFICANT and old is None:
            failed = True
            print("::error::%s %s differs from the original binary: %s" % (
                mod, name, new))
        elif old is not None and new != old:
            changed = True
            print("changed: %s %s: %s -> %s" % (mod, name, old, new))
    if changed and not failed:
        print("::notice::%s can be updated: python tools/vc6_compare.py "
              "--update %s" % (file_name, file_name))
    return not failed


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--check", metavar="FILE")
    group.add_argument("--update", metavar="FILE")
    args = parser.parse_args()
    statuses = compare()
    if args.update:
        with open(args.update, "w", encoding="latin-1", newline="\n") as f:
            f.write(format_statuses(statuses))
        return
    sys.exit(0 if check(statuses, args.check) else 1)


if __name__ == "__main__":
    main()
